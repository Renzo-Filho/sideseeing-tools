"""Local viewer for a SideSeeing workspace: interactive pages plus the static report at /report."""
import time
from pathlib import Path
from urllib.parse import quote

import uvicorn
from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse, HTMLResponse
from fastapi.staticfiles import StaticFiles
from jinja2 import Environment, PackageLoader, select_autoescape

from sideseeing_tools.dataviz import api, assessment
from sideseeing_tools.workspace import list_frames

STATIC_DIR = Path(__file__).resolve().parent.parent / "templates" / "static"


def create_app(workspace_dir):
    """The viewer application for a workspace directory created by SideSeeingWorkspace."""
    workspace = Path(workspace_dir).resolve()

    if not workspace.is_dir():
        raise NotADirectoryError(f"Workspace not found: {workspace}")

    app = FastAPI(title="SideSeeing Viewer")
    app.state.workspace = workspace
    app.state.extraction_jobs = {}
    env = Environment(loader=PackageLoader("sideseeing_tools", "templates"), autoescape=select_autoescape())
    template = env.get_template("viewer.html")
    started = int(time.time())

    @app.get("/", response_class=HTMLResponse)
    def viewer():
        return template.render(
            title=f"SideSeeing Viewer - {workspace.name}",
            samples=[dict(name=route) for route in api.list_routes(workspace)],
            analysis_files={
                route: f"api/viewer/assessment/{quote(route)}" for route in assessment.routes_with_events(workspace)
            },
            report_url="report/" if (workspace / "report" / "index.html").is_file() else None,
            cache_buster=started,
        )

    @app.get("/api/viewer/assessment/{route}")
    def route_assessment(route: str):
        if route not in api.list_routes(workspace):
            raise HTTPException(status_code=404, detail="Unknown route.")

        frames = [path.name for path in list_frames(api.route_frames_dir(workspace, route))]
        data = assessment.route_assessment(workspace, route, frames)

        if data is None:
            raise HTTPException(status_code=404, detail="No sidewalk events for this route.")
        return data

    @app.get("/report/{path:path}")
    def report(path: str):
        """Serves report/ as generated by SideSeeingWorkspace.generate_report."""
        root = (workspace / "report").resolve()
        target = (root / path).resolve()

        if target.is_dir():
            target = target / "index.html"
        if not target.is_relative_to(root) or not target.is_file():
            raise HTTPException(status_code=404, detail="Report file not found.")
        return FileResponse(target)

    app.include_router(api.router)
    app.mount("/static", StaticFiles(directory=STATIC_DIR), name="static")
    return app


def start_server(workspace_dir: str, port: int = 5000, host: str = "127.0.0.1"):
    """
    Serves the viewer for a workspace. The default host only accepts local connections;
    use SSH port forwarding to reach it remotely. Binding to 0.0.0.0 exposes unredacted
    frames to the network.
    """
    print(f"Starting SideSeeing viewer at http://{host}:{port}")
    uvicorn.run(create_app(workspace_dir), host=host, port=port, log_level="info")
